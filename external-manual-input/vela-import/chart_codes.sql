-- =============================================================================
-- Vela Chart Codes (Mermaid diagrams)
--
-- Stores user-authored Mermaid chart source ("chart codes"). Accessed only
-- through the Netlify function /api/chart-codes (service-role key), from the
-- web app, the vela-mobile app, and the Vela PC app.
--
-- The table predates this file (it was created ad hoc in the Supabase console);
-- this DDL documents the deployed shape and supports fresh setups. The
-- function tolerates missing product_id / product_name columns for legacy
-- databases (see isMissingColumn in netlify/functions/chart-codes.ts).
-- =============================================================================

create table if not exists public.chart_codes (
  id bigint generated by default as identity primary key,
  title text not null default 'New Chart',
  mmd_code text not null default '',            -- Mermaid source (may include YAML frontmatter)
  product_id text,                              -- soft link to products.id (string, no FK)
  product_name text,                            -- denormalized product label (legacy)
  protected boolean not null default false,     -- system charts (Product Map) cannot be deleted
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists chart_codes_updated_at_idx on public.chart_codes (updated_at desc);

-- All server access goes through Netlify functions with the service-role key.
-- Lock the table down against direct client access.
alter table public.chart_codes enable row level security;

-- No policies => anon/authenticated clients can never read or write this table.
